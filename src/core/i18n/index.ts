// ── Store ─────────────────────────────────────────────────────

function detectDeviceLang(): LangCode {
  try {
    const locale = getLocales()[0]?.languageCode ?? 'en';
    const supported = LANGUAGES.map(l => l.code);
    return supported.includes(locale as LangCode) ? (locale as LangCode) : 'en';
  } catch {
    return 'en';
  }
}

interface I18nState {
  lang: LangCode;
  t: (key: string) => string;
  setLang: (lang: LangCode) => Promise<void>;
  loadSavedLang: () => Promise<void>;
}

export const useI18n = create<I18nState>((set, get) => ({
  lang: detectDeviceLang(),

  t: (key: string) => {
    const { lang } = get();
    return translations[lang]?.[key] ?? translations['en']?.[key] ?? key;
  },

  setLang: async (lang: LangCode) => {
    await AsyncStorage.setItem('@pathrix_lang', lang);
    set({ lang });
  },

  loadSavedLang: async () => {
    try {
      const saved = await AsyncStorage.getItem('@pathrix_lang');
      if (saved && LANGUAGES.some(l => l.code === saved)) {
        set({ lang: saved as LangCode });
      }
    } catch { /* keep device default */ }
  },
}));
